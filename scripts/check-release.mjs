import fs from 'node:fs';
const pkg = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const api = JSON.parse(fs.readFileSync(new URL('../server/package.json', import.meta.url), 'utf8'));
const changelog = fs.readFileSync(new URL('../CHANGELOG.md', import.meta.url), 'utf8');
const tag = process.env.RELEASE_TAG || process.env.GITHUB_REF_NAME;
const version = pkg.version;
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('package.json must contain an X.Y.Z version');
if (api.version !== version) throw new Error(`API version ${api.version} differs from ${version}`);
const heading = new RegExp(`^##\\s+\\[?v?${version.replaceAll('.', '\\.') }\\]?(?=\\s|$)`, 'm');
if (!heading.test(changelog)) throw new Error(`CHANGELOG.md needs a heading for ${version} (e.g. ## ${version} or ## [${version}])`);
if (tag && /^v\d/.test(tag) && tag !== `v${version}`) throw new Error(`Tag ${tag} does not match package version v${version}`);
console.log(`Release metadata verified: v${version}`);
